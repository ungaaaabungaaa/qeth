import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { writeFile } from 'node:fs/promises';
import { startFixture } from './fixture-server.mjs';
const execute = promisify(execFile);
const site = await startFixture();
try {
  const commands = [
    ['rag', 'scan', 'examples/chunks.json'],
    ['trace', 'examples/trace.json', '--baseline', 'examples/baseline.json'],
    ['crawl', site.url, '--allow-local', '--delay', '0'],
    ['mission', 'plan', 'examples/survey-area.geojson', '--spacing', '30']
  ];
  let text = '# Captured example session\n\nGenerated by `npm run demo` from local fixtures. The survey is synthetic and the server URL is temporary. These outputs are measured program results.\n\n';
  for (const args of commands) {
    const { stdout, stderr } = await execute(process.execPath, ['dist/cli.js', ...args], { timeout: 15000 });
    const capture = `$ qeth ${args.join(' ')}\n${stdout}${stderr}`;
    process.stdout.write(capture + '\n');
    text += '```text\n' + capture + '```\n\n';
  }
  await writeFile('docs/example-session.md', text);
} finally { await site.close(); }
